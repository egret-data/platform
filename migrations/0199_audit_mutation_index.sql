-- DG #3 (Governance Overview), spec §3.3/§3.4: the governance feed reads
-- `kind = 'mutation'` rows newest first. PDP decision rows share the table and
-- dominate it (one per authorisation), so without a partial index the feed's
-- `ORDER BY ts DESC, id DESC LIMIT n` walks `audit_log_ts_idx` through every
-- decision row between two governance events.
--
-- **Built without `CONCURRENTLY`, so it blocks audit inserts while it builds.**
-- sqlx runs each migration file in one transaction, `CREATE INDEX
-- CONCURRENTLY` cannot run in a transaction block, and no migration in this
-- repo opts out (`-- no-transaction`). The build holds a SHARE lock on
-- `audit.audit_log` for as long as it reads the table: the PDP's decision rows
-- and every mutation event wait (the sink buffers, then drops; a governance
-- write waits with them). On a large audit table, run the migration in a quiet
-- window, or prune first.
CREATE INDEX audit_log_mutation_ts_idx ON audit.audit_log (ts DESC, id DESC) WHERE kind = 'mutation';
