//! What crosses the proxy in each direction.
//!
//! Requests: the client controls every header it sends, so the rule is "name what goes
//! upstream", not "remove what is dangerous". Anything `X-Egret-*` is removed (the pod
//! trusts `X-Egret-App-Token` as the viewer's identity, so only the proxy may set it); the
//! apps cookie, the client's `Authorization` and `Origin` never reach the pod; marimo's own
//! `Marimo-Server-Token` and `Marimo-Session-Id` pass through (the first is skew protection
//! and not secret, the second is how marimo finds the session a request belongs to);
//! `X-Notebook-Id` — which marimo uses to pick the directory `/public` serves from — is
//! overwritten or removed, never passed through.
//!
//! Responses: the pod's cookies and CORS headers are dropped (the apps origin has one
//! cookie, egret's, and no page may be given cross-origin read access), and every response
//! says only egret may frame it.

use axum::http::{header, HeaderMap, HeaderName, HeaderValue};
use uuid::Uuid;

/// Hop-by-hop (RFC 9110 §7.6.1) plus the headers an HTTP client rebuilds itself.
const NEVER_FORWARDED: [&str; 12] = [
    "connection",
    "keep-alive",
    "proxy-authenticate",
    "proxy-authorization",
    "te",
    "trailer",
    "trailers",
    "transfer-encoding",
    "upgrade",
    "host",
    "content-length",
    "expect",
];
/// Regenerated by the upstream WebSocket client.
const WS_HANDSHAKE: [&str; 5] = [
    "sec-websocket-key",
    "sec-websocket-version",
    "sec-websocket-extensions",
    "sec-websocket-accept",
    "sec-websocket-protocol",
];
/// The client's identity on the APPS origin and its claims about where it came from.
const CLIENT_ONLY: [&str; 3] = ["cookie", "authorization", "origin"];

pub struct Inject<'a> {
    /// The per-session query token (`ega_…`); sent as `X-Egret-App-Token`. `None` for a
    /// static file, which needs no identity and should not cost a token.
    pub app_token: Option<&'a str>,
    /// The pod's marimo token (`--token-password`); sent as `Authorization: Bearer`.
    pub marimo_token: &'a str,
    /// The notebook file this request was authorized for, if it named one.
    pub pinned_notebook: Option<&'a str>,
}

/// The headers to send upstream for a client request.
pub fn upstream_headers(client: &HeaderMap, inject: &Inject) -> HeaderMap {
    let mut out = HeaderMap::new();
    for (name, value) in client {
        let n = name.as_str();
        if NEVER_FORWARDED.contains(&n)
            || WS_HANDSHAKE.contains(&n)
            || CLIENT_ONLY.contains(&n)
            || n.starts_with("x-egret-")
            || n == "x-notebook-id"
        {
            continue;
        }
        out.append(name.clone(), value.clone());
    }
    if let Ok(v) = HeaderValue::from_str(&format!("Bearer {}", inject.marimo_token)) {
        out.insert(header::AUTHORIZATION, v);
    }
    if let Some(Ok(v)) = inject.app_token.map(HeaderValue::from_str) {
        out.insert(HeaderName::from_static("x-egret-app-token"), v);
    }
    if let Some(Ok(v)) = inject.pinned_notebook.map(HeaderValue::from_str) {
        out.insert(HeaderName::from_static("x-notebook-id"), v);
    }
    out
}

/// The headers to send to the browser for an upstream response.
pub fn response_headers(upstream: &HeaderMap, egret_origin: &str) -> HeaderMap {
    let mut out = HeaderMap::new();
    for (name, value) in upstream {
        let n = name.as_str();
        if NEVER_FORWARDED.contains(&n)
            || n == "set-cookie"
            || n == "x-frame-options"
            || n.starts_with("access-control-")
        {
            continue;
        }
        out.append(name.clone(), value.clone());
    }
    // `append`, not `insert`: if marimo sends a policy of its own, both are enforced.
    if let Ok(v) = HeaderValue::from_str(&format!("frame-ancestors {egret_origin}")) {
        out.append(header::CONTENT_SECURITY_POLICY, v);
    }
    out.insert(
        header::X_CONTENT_TYPE_OPTIONS,
        HeaderValue::from_static("nosniff"),
    );
    out
}

/// The notebook file a request names through its query string (`?file=…`, on the editor's
/// page load and on the `/ws` upgrade).
///
/// `Err(())` when it is named twice: two values are two different requests depending on
/// who reads the query, and the proxy checks one while marimo might read the other.
#[allow(clippy::result_unit_err)]
pub fn named_file(query: Option<&str>) -> Result<Option<String>, ()> {
    let mut found = None;
    for (k, v) in url::form_urlencoded::parse(query.unwrap_or("").as_bytes()) {
        if k == "file" {
            if found.is_some() {
                return Err(());
            }
            found = Some(v.into_owned());
        }
    }
    Ok(found)
}

/// `<uuid>.py` — the one spelling of an app's draft file in an edit pod's directory. Anything
/// else (a path, `../x.py`, a trailing newline, upper case) is not an app and is refused.
pub fn app_id_of_file(file: &str) -> Option<Uuid> {
    let stem = file.strip_suffix(".py")?;
    let id = Uuid::parse_str(stem).ok()?;
    (id.hyphenated().to_string() == stem).then_some(id)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn headers(pairs: &[(&str, &str)]) -> HeaderMap {
        let mut h = HeaderMap::new();
        for (k, v) in pairs {
            h.append(
                HeaderName::from_bytes(k.as_bytes()).unwrap(),
                HeaderValue::from_str(v).unwrap(),
            );
        }
        h
    }

    fn inject(pinned: Option<&'static str>) -> Inject<'static> {
        Inject {
            app_token: Some("ega_real"),
            marimo_token: "m-secret",
            pinned_notebook: pinned,
        }
    }

    fn get<'a>(h: &'a HeaderMap, k: &str) -> Vec<&'a str> {
        h.get_all(k).iter().map(|v| v.to_str().unwrap()).collect()
    }

    #[test]
    fn a_client_supplied_x_egret_header_never_reaches_the_pod() {
        let client = headers(&[
            ("x-egret-app-token", "ega_forged"),
            ("X-Egret-App-Token", "ega_forged2"),
            ("x-egret-user", "admin"),
            ("x-egret-anything-else", "1"),
            ("accept", "text/html"),
        ]);
        let out = upstream_headers(&client, &inject(None));
        assert_eq!(
            get(&out, "x-egret-app-token"),
            ["ega_real"],
            "exactly one, ours"
        );
        assert!(out.get("x-egret-user").is_none());
        assert!(out.get("x-egret-anything-else").is_none());
        assert_eq!(get(&out, "accept"), ["text/html"]);
    }

    #[test]
    fn a_static_request_carries_no_token_at_all_and_still_no_forged_one() {
        let client = headers(&[("x-egret-app-token", "ega_forged")]);
        let out = upstream_headers(
            &client,
            &Inject {
                app_token: None,
                marimo_token: "m-secret",
                pinned_notebook: None,
            },
        );
        assert!(out.get("x-egret-app-token").is_none());
    }

    #[test]
    fn the_apps_cookie_and_the_clients_credentials_stay_on_this_side() {
        let client = headers(&[
            ("cookie", "egret_apps_grant=egc_secret"),
            ("authorization", "Bearer client-supplied"),
            ("origin", "https://apps.egret.example"),
        ]);
        let out = upstream_headers(&client, &inject(None));
        assert!(out.get("cookie").is_none());
        assert!(out.get("origin").is_none());
        assert_eq!(
            get(&out, "authorization"),
            ["Bearer m-secret"],
            "the pod's token, not the client's"
        );
    }

    #[test]
    fn hop_by_hop_and_websocket_handshake_headers_are_not_forwarded() {
        let client = headers(&[
            ("connection", "Upgrade"),
            ("upgrade", "websocket"),
            ("keep-alive", "timeout=5"),
            ("te", "trailers"),
            ("transfer-encoding", "chunked"),
            ("host", "apps.egret.example"),
            ("content-length", "5"),
            ("proxy-authorization", "x"),
            ("sec-websocket-key", "k"),
            ("sec-websocket-version", "13"),
            ("sec-websocket-extensions", "permessage-deflate"),
            ("sec-websocket-protocol", "p"),
        ]);
        let out = upstream_headers(&client, &inject(None));
        let names: Vec<&str> = out.keys().map(|k| k.as_str()).collect();
        assert_eq!(names, ["authorization", "x-egret-app-token"], "{names:?}");
    }

    #[test]
    fn marimos_session_and_skew_headers_pass_through() {
        let client = headers(&[
            ("marimo-session-id", "s_abc"),
            ("marimo-server-token", "skew"),
            ("content-type", "application/json"),
        ]);
        let out = upstream_headers(&client, &inject(None));
        assert_eq!(get(&out, "marimo-session-id"), ["s_abc"]);
        assert_eq!(get(&out, "marimo-server-token"), ["skew"]);
        assert_eq!(get(&out, "content-type"), ["application/json"]);
    }

    #[test]
    fn x_notebook_id_is_pinned_or_removed_never_passed_through() {
        let client = headers(&[("x-notebook-id", "../../etc")]);
        let removed = upstream_headers(&client, &inject(None));
        assert!(removed.get("x-notebook-id").is_none());
        let pinned = upstream_headers(&client, &inject(Some("0a1b.py")));
        assert_eq!(get(&pinned, "x-notebook-id"), ["0a1b.py"]);
    }

    #[test]
    fn response_cookies_and_cors_are_dropped_and_only_egret_may_frame() {
        let upstream = headers(&[
            ("set-cookie", "marimo=1"),
            ("access-control-allow-origin", "*"),
            ("access-control-allow-credentials", "true"),
            ("x-frame-options", "SAMEORIGIN"),
            ("content-type", "text/html"),
            ("transfer-encoding", "chunked"),
            ("content-security-policy", "default-src 'self'"),
        ]);
        let out = response_headers(&upstream, "https://egret.example");
        assert!(out.get("set-cookie").is_none());
        assert!(out.get("access-control-allow-origin").is_none());
        assert!(out.get("access-control-allow-credentials").is_none());
        assert!(out.get("x-frame-options").is_none());
        assert!(out.get("transfer-encoding").is_none());
        assert_eq!(get(&out, "content-type"), ["text/html"]);
        assert_eq!(
            get(&out, "content-security-policy"),
            [
                "default-src 'self'",
                "frame-ancestors https://egret.example"
            ],
            "marimo's own policy is kept and ours added: both are enforced"
        );
        assert_eq!(get(&out, "x-content-type-options"), ["nosniff"]);
    }

    #[test]
    fn the_named_file_is_read_from_the_query_and_a_repeated_one_is_refused() {
        assert_eq!(named_file(None), Ok(None));
        assert_eq!(named_file(Some("a=1")), Ok(None));
        assert_eq!(
            named_file(Some("file=x.py&session_id=s")),
            Ok(Some("x.py".into()))
        );
        assert_eq!(named_file(Some("file=a%2Fb.py")), Ok(Some("a/b.py".into())));
        assert_eq!(named_file(Some("file=a.py&file=b.py")), Err(()));
    }

    #[test]
    fn only_the_exact_draft_file_spelling_names_an_app() {
        let id = Uuid::new_v4();
        assert_eq!(app_id_of_file(&format!("{id}.py")), Some(id));
        assert_eq!(
            app_id_of_file(&format!("{id}.py\n")),
            None,
            "a trailing newline"
        );
        assert_eq!(
            app_id_of_file(&format!("{}.py", id.to_string().to_uppercase())),
            None
        );
        assert_eq!(app_id_of_file(&format!("../{id}.py")), None);
        assert_eq!(app_id_of_file(&format!("sub/{id}.py")), None);
        assert_eq!(
            app_id_of_file(&format!("{}.py", id.simple())),
            None,
            "unhyphenated"
        );
        assert_eq!(app_id_of_file(&format!("{id}")), None);
        assert_eq!(app_id_of_file("notes.py"), None);
        assert_eq!(app_id_of_file(""), None);
    }
}
