/**
 * The nine datasets the "ZZ Chart Parity" harness is built on, and the metrics its charts name.
 *
 * These are Trino `VALUES` literals materialised from Metabase's OWN query results against its
 * H2 Sample Database, so both dashboards plot byte-identical numbers and any visual difference
 * is egret's rendering rather than its data. They are recovered verbatim from the `demo`
 * workspace via `GET /api/ws/demo/datasets/{id}` — not retyped. Every measurement in chart
 * parity PRs 01–06 was taken against exactly these rows, and a literal that differs by one row
 * silently changes what a future comparison means.
 *
 * The anchor that proves they survived the trip: `MB Monthly`'s first row is
 * `2026-01-01 → 205 orders / 11,094.7 revenue`. `datasets.test.ts` asserts it.
 *
 * OUT OF SCOPE: Metabase's own 19 cards and its H2 database. They live in a separate store that
 * a reset of egret's Postgres does not touch, and rebuilding them needs Metabase's card API.
 *
 * METRICS ARE NOT COLUMNS. A chart may only name a metric this file declares with an
 * expression (`SUM(revenue)`); a spec naming a bare column comes back `unknown metric` at
 * RENDER time — the chart saves cleanly and fails only when someone opens the dashboard.
 * `assertMetricsDeclared` below turns that into a load-time failure instead.
 */

export interface HarnessColumn {
  column_name: string;
  data_type: string;
  /** Drives the studio's monthly-grouping default; see `params.ts`. */
  is_temporal: boolean;
}

export interface HarnessMetric {
  metric_name: string;
  /** An aggregate over the dataset's columns, e.g. `SUM(revenue)`. */
  expression: string;
}

export interface HarnessDataset {
  name: string;
  description: string;
  /** The dataset's virtual source. Created with `source: {kind: "virtual", sql}`. */
  sql: string;
  /**
   * The columns the server inferred when this dataset was created. Declared here so the seed
   * can build chart params BEFORE it has to round-trip the created dataset, and so a change in
   * Trino's type inference is caught (`assertColumnsMatch`) rather than silently reshaping the
   * charts that were measured against these.
   */
  columns: HarnessColumn[];
  metrics: HarnessMetric[];
}

