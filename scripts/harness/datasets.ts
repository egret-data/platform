/** Look a dataset up by name, loudly. A typo here would otherwise surface as a 404 mid-seed. */
export function datasetByName(name: string): HarnessDataset {
  const ds = DATASETS.find((d) => d.name === name);
  if (!ds) {
    throw new Error(`no harness dataset named "${name}" — have: ${DATASETS.map((d) => d.name).join(", ")}`);
  }
  return ds;
}

/** One chart's claim on a dataset's metrics, as `assertMetricsDeclared` wants to hear it. */
export interface MetricUse {
  /** Chart name, for the error message — the whole point is to name the culprit. */
  chart: string;
  dataset: string;
  /** Every metric the chart's spec will name. `undefined` entries are ignored. */
  metrics: (string | undefined)[];
}

/**
 * The first of the four API-level traps, as a checked invariant rather than a comment.
 *
 * A chart whose spec names something that is not a declared dataset metric saves with a 200 and
 * renders `unknown metric`. Nothing between the two notices, so the harness has shipped that
 * state before. This runs over the whole chart list BEFORE the seed creates anything, so the
 * failure is a message naming the chart and the metric instead of a half-built workspace.
 *
 * It is deliberately a pure function over the declarations in this file, not a check against
 * the live server: it must fail in `datasets.test.ts` with no instance running.
 */
export function assertMetricsDeclared(uses: MetricUse[]): void {
  const problems: string[] = [];
  for (const use of uses) {
    const ds = datasetByName(use.dataset);
    const declared = new Set(ds.metrics.map((m) => m.metric_name));
    for (const m of use.metrics) {
      if (m === undefined) continue;
      if (!declared.has(m)) {
        const known = [...declared].join(", ") || "(none)";
        problems.push(
          `${use.chart}: "${m}" is not a declared metric of ${ds.name} — declared: ${known}. ` +
          `A chart that names a bare column renders "unknown metric".`,
        );
      }
    }
  }
  if (problems.length > 0) {
    throw new Error(`undeclared chart metrics:\n  ${problems.join("\n  ")}`);
  }
}

/**
 * The columns this file claims a dataset has, against the ones the server actually inferred
 * after creating it. A mismatch means Trino typed a `VALUES` literal differently than it did
 * when PRs 01–06 measured, which would silently reshape every chart on that dataset — most
 * dangerously `is_temporal`, which decides whether the monthly-grouping default fires.
 */
export function assertColumnsMatch(ds: HarnessDataset, actual: HarnessColumn[]): void {
  const key = (c: HarnessColumn) => `${c.column_name}:${c.data_type}:${c.is_temporal}`;
  const want = ds.columns.map(key);
  const got = actual.map((c) => key({ column_name: c.column_name, data_type: c.data_type, is_temporal: c.is_temporal }));
  if (want.join("|") !== got.join("|")) {
    throw new Error(
      `${ds.name}: the server inferred different columns than the harness declares.\n` +
      `  declared: ${want.join(", ")}\n  inferred: ${got.join(", ")}`,
    );
  }
}
